#!/usr/bin/env node
/**
 * Regenerate the schema baseline from a live database.
 *
 * The baseline must always be MACHINE-GENERATED. A hand-written one is a guess,
 * and it is exactly the details a human would skip — generated columns, sequence
 * ownership, enum member order, partial-index predicates, view bodies — that
 * decide whether a migration behaves the same in CI as in production.
 *
 * Run this only when the manually-owned base schema changes (rare, and ideally
 * never again). Ordinary schema changes are knex migrations and must NOT be
 * folded into the baseline.
 *
 * Usage:  node scripts/regenerate-baseline.cjs [--url <postgres-url>] [--pg-dump <path>]
 */
const fs = require('fs')
const path = require('path')
const { execFileSync } = require('child_process')
const { Client } = require('pg')

const OUT_DIR = path.join(__dirname, '..', 'db', 'baseline')
const MIGRATIONS_DIR = path.join(__dirname, '..', 'migrations')

function arg(name, fallback) {
  const i = process.argv.indexOf(name)
  return i > -1 ? process.argv[i + 1] : fallback
}

function readEnvUrl() {
  const envPath = path.join(__dirname, '..', '.env.local')
  if (!fs.existsSync(envPath)) return process.env.DATABASE_URL
  const line = fs.readFileSync(envPath, 'utf8').split('\n').filter((l) => /^DATABASE_URL=/.test(l)).pop()
  if (!line) return process.env.DATABASE_URL
  return line.replace(/^DATABASE_URL=/, '').trim().replace(/^["']|["']$/g, '')
}

function findPgDump() {
  const explicit = arg('--pg-dump')
  if (explicit) return explicit
  const candidates = [
    'pg_dump',
    '/Library/PostgreSQL/18/bin/pg_dump',
    '/opt/homebrew/opt/libpq/bin/pg_dump',
    '/usr/local/opt/libpq/bin/pg_dump',
  ]
  for (const c of candidates) {
    try {
      execFileSync(c, ['--version'], { stdio: 'pipe' })
      return c
    } catch {
      /* try the next one */
    }
  }
  throw new Error(
    'pg_dump not found. Install the Postgres client tools or pass --pg-dump <path>.\n' +
      '  The baseline must come from pg_dump — never hand-write it.',
  )
}

async function main() {
  const raw = arg('--url', readEnvUrl())
  if (!raw) throw new Error('No DATABASE_URL. Pass --url <postgres-url>.')
  const url = new URL(raw)
  url.searchParams.delete('sslmode')

  const pgDump = findPgDump()
  const pgDumpVersion = execFileSync(pgDump, ['--version']).toString().trim()

  // No --schema=public: naming the schema makes pg_dump emit `CREATE SCHEMA
  // public`, which fails on a fresh database where it already exists.
  const dumped = execFileSync(
    pgDump,
    ['--schema-only', '--no-owner', '--no-privileges', url.toString()],
    { maxBuffer: 256 * 1024 * 1024 },
  ).toString()

  // pg_dump 17+ brackets its output with psql-only `\restrict` / `\unrestrict`
  // guards, which are a syntax error through a driver. The loader strips them
  // too; doing it here keeps the committed artifact directly loadable.
  const sql = dumped
    .split('\n')
    .filter((line) => !/^\\(un)?restrict\s/.test(line))
    .join('\n')

  // Guard against a dump that accidentally carried rows. Anchored at column 0
  // on purpose: pg_dump emits data at the top level, while the INSERTs that
  // legitimately appear inside trigger function bodies are always indented.
  if (/^COPY .* FROM stdin;/m.test(sql) || /^INSERT INTO /m.test(sql)) {
    throw new Error('The dump contains data statements. It must be --schema-only.')
  }

  const client = new Client({ connectionString: url.toString(), ssl: false })
  await client.connect()
  const applied = (await client.query('SELECT name FROM knex_migrations ORDER BY name')).rows.map((r) => r.name)
  const serverVersion = (await client.query('SHOW server_version')).rows[0].server_version
  await client.end()

  const onDisk = fs.readdirSync(MIGRATIONS_DIR).filter((f) => f.endsWith('.cjs')).sort()
  const ghosts = applied.filter((n) => !onDisk.includes(n))
  if (ghosts.length) {
    throw new Error(
      `The source database has ${ghosts.length} migration(s) recorded that are not on disk:\n  ` +
        ghosts.join('\n  ') +
        '\nKnex refuses to run in that state. Reconcile before regenerating.',
    )
  }

  fs.mkdirSync(OUT_DIR, { recursive: true })
  fs.writeFileSync(path.join(OUT_DIR, 'schema-baseline.sql'), sql)
  fs.writeFileSync(
    path.join(OUT_DIR, 'baseline.json'),
    JSON.stringify(
      {
        $comment: 'Machine-generated by scripts/regenerate-baseline.cjs. Do not hand-edit.',
        generatedAt: new Date().toISOString().slice(0, 10),
        sourceDatabase: `${url.hostname}:${url.port}${url.pathname} (local development)`,
        sourceServerVersion: serverVersion,
        pgDumpVersion,
        schemaFile: 'schema-baseline.sql',
        stampedMigrationCount: applied.length,
        stampedMigrations: applied,
      },
      null,
      2,
    ) + '\n',
  )

  const pending = onDisk.filter((f) => !applied.includes(f))
  console.log(`[baseline] wrote ${sql.split('\n').length} lines from ${url.hostname}${url.pathname}`)
  console.log(`[baseline] stamped ${applied.length} migrations; ${pending.length} will run after bootstrap`)
  pending.forEach((p) => console.log(`             ${p}`))
}

main().catch((err) => {
  console.error('[baseline] FAILED:', err.message)
  process.exit(1)
})
