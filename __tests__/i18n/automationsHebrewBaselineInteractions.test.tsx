const norm = (html: string) => html.replace(/«[^»]*»/g, '«id»').replace(/_[rR]_[0-9a-zA-Z]*_/g, '«id»').replace(/:r[0-9a-z]+:/g, '«id»')
const set = (overrides: Partial<typeof automationsEnv>) => Object.assign(automationsEnv, overrides)
const calls = () => JSON.parse(JSON.stringify(automationsEnv.calls))
const dialog = () => norm([...document.querySelectorAll('[role="dialog"]')].map((d) => d.outerHTML).join('\n'))
const click = async (el: Element | null | undefined) => act(async () => void fireEvent.click(el!))
const wait = (ms = 0) => act(async () => void (await new Promise((r) => setTimeout(r, ms))))
const type = (el: Element | null | undefined, value: string) => act(async () => void fireEvent.change(el!, { target: { value } }))
const btn = (text: string, root: ParentNode = document) => [...root.querySelectorAll('button')].find((b) => b.textContent?.trim() === text)
const menuItem = (text: string) => [...document.querySelectorAll('[role="menuitem"]')].find((b) => b.textContent === text)
const dlg = () => document.querySelector('[role="dialog"]')!
const selects = () => [...dlg().querySelectorAll('select')]
const mount = async (ent?: typeof EXPIRED) => render(await automationsShell(null, await automationsPage('automations'), ent))
const row = (name: string) => [...document.querySelectorAll('aside button')].find((b) => b.textContent?.includes(name))!.parentElement!
const openMenu = (name: string) => click(row(name).querySelector('button[aria-haspopup="menu"]'))

beforeAll(() => {
  Object.assign(HTMLElement.prototype, { showPopover() {}, hidePopover() {}, togglePopover() {} })
  vi.spyOn(console, 'log').mockImplementation(() => {})
  vi.spyOn(console, 'warn').mockImplementation(() => {})
  vi.spyOn(console, 'error').mockImplementation(() => {})
  let seq = 0
  vi.spyOn(Math, 'random').mockImplementation(() => (seq = (seq % 997) + 1) / 1000)
  vi.useFakeTimers({ toFake: ['Date'] })
  vi.setSystemTime(NOW)
})
afterAll(() => vi.useRealTimers())
afterEach(() => {
  cleanup()
  resetAutomationsEnv()
})

describe('Hebrew baseline — automations workspace interactions', () => {
  test('library search + tabs, row menu, toggle + undo, duplicate, delete, run log', async () => {
    const out: Record<string, unknown> = {}
    const { container } = await mount()
    const search = container.querySelector('input[type="search"]')
    await type(search, 'מעקב')
    out.search = norm(container.innerHTML)
    await type(search, 'zzz')
    out.searchEmpty = norm(container.innerHTML)
    await type(search, '')
    const tabs = [...container.querySelectorAll('button[aria-pressed]')].filter((b) => !b.closest('aside'))
    await click(tabs[1])
    out.tab = norm(container.querySelector('section')!.innerHTML)
    await click(tabs[0])
    await openMenu('מענה ראשון לליד חדש')
    out.menu = norm(document.querySelector('[role="menu"]')!.outerHTML)
    await click(menuItem('שכפל'))
    await wait()
    await click(row('מענה ראשון לליד חדש').querySelector('button[aria-pressed]'))
    await wait()
    await act(async () => automationsEnv.undo?.())
    await wait()
    set({ results: { setAutomationStatus: { ok: false } } })
    await click(row('משימה על ליד מעוניין').querySelector('button[aria-pressed]'))
    await wait()
    set({ results: { setAutomationStatus: 'throw' } })
    await click(row('משימה על ליד מעוניין').querySelector('button[aria-pressed]'))
    await wait()
    set({ results: {} })
    await openMenu('מעקב טופס מהאתר')
    await click(menuItem('מחק'))
    out.deleteConfirm = dialog()
    await click(btn('מחק', dlg()))
    await wait()
    await openMenu('מענה ראשון לליד חדש')
    await click(menuItem('יומן פעילות'))
    await wait()
    out.log = dialog()
    await click(dlg().querySelector('button[aria-label]'))
    set({ results: { listActivityForAutomationAction: { ok: true, rows: [] } } })
    await openMenu('מענה ראשון לליד חדש')
    await click(menuItem('יומן פעילות'))
    await wait()
    out.logEmpty = dialog()
    await click(dlg().querySelector('button[aria-label]'))
    set({ results: { listActivityForAutomationAction: { ok: false, reason: 'forbidden' } } })
    await openMenu('מענה ראשון לליד חדש')
    await click(menuItem('יומן פעילות'))
    await wait()
    out.calls = calls()
    expect(out).toMatchSnapshot()
  })

  test('the sheet: a new automation, conditions, events, actions, timing, previews, save refusals', async () => {
    const out: Record<string, unknown> = {}
    const { container } = await mount()
    await click(btn('אוטומציה חדשה', container.querySelector('section')!))
    out.blank = dialog()
    await click(btn('הוספת תנאי', dlg()))
    await type(selects()[1], 'source')
    out.condition = dialog()
    await type(selects()[1], 'email')
    await type(selects()[2], 'exists')
    out.valueless = dialog()
    await click(btn('הסרה', dlg()))
    await type(dlg().querySelector('input'), 'אוטומציה לבדיקה')
    const [subject, body] = [dlg().querySelectorAll('input')[1], dlg().querySelector('textarea')]
    await act(async () => void fireEvent.focus(subject!))
    await type(subject, 'שלום ')
    await click(btn('שם הליד', dlg()))
    await type(body, 'גוף')
    await click(btn('הוספת כפתור לאימייל', dlg()))
    await wait(600)
    out.email = dialog()
    await click(btn('אחרי יום', dlg()))
    for (const reason of ['name_required', 'cta_url_invalid', 'mystery']) {
      set({ results: { createAutomation: { ok: false, reason } } })
      await click(btn('שמור אוטומציה', dlg()))
      await wait()
      out[`refused:${reason}`] = norm(dlg().querySelector('[role="alert"]')?.outerHTML ?? '')
    }
    set({ results: { sendTestEmail: { ok: false, reason: 'no_recipient' } } })
    await click(btn('שלח אליי בדיקה', dlg()))
    await wait()
    out.testRefused = norm(dlg().querySelector('[role="alert"]')?.outerHTML ?? '')
    set({ results: {} })
    await click(btn('שלח אליי בדיקה', dlg()))
    await wait()
    await type(selects()[0], 'lead.status_changed')
    await type(selects()[1], 'task.create')
    await wait()
    out.task = dialog()
    await type(selects()[0], 'appointment.booked')
    await type(selects()[1], 'whatsapp.send')
    await wait()
    out.whatsappPick = dialog()
    await type(selects()[2], '5')
    await wait(500)
    out.whatsapp = dialog()
    await type(selects()[0], 'form.submitted')
    await wait()
    out.form = dialog()
    await type(selects()[0], 'lead.created')
    await type(selects()[1], 'quote.create')
    await wait()
    out.quote = dialog()
    set({ results: { createAutomation: { ok: true, id: 31 } } })
    await click(btn('שמור אוטומציה', dlg()))
    await wait()
    out.calls = calls()
    expect(out).toMatchSnapshot()
  })

  test('the sheet: editing each saved shape; the expired locks; the library install dialog', async () => {
    const out: Record<string, unknown> = {}
    const { container } = await mount()
    for (const name of ['מענה ראשון לליד חדש', 'משימה על ליד מעוניין', 'תזכורת פגישה בוואטסאפ', 'מעקב טופס מהאתר']) {
      await click([...container.querySelectorAll('aside button')].find((b) => b.textContent?.includes(name)))
      await wait(600)
      out[`edit:${name}`] = dialog()
      if (name === 'משימה על ליד מעוניין') {
        await click(btn('שמור שינויים', dlg()))
        await wait()
        await click([...container.querySelectorAll('aside button')].find((b) => b.textContent?.includes(name)))
        await wait()
      }
      await click(dlg().querySelector('button[aria-label]'))
    }
    const cells = [...container.querySelectorAll('section button')].filter((b) => b.getAttribute('aria-label')?.includes(' · '))
    out.cells = cells.map((b) => b.getAttribute('aria-label'))
    await click(cells.find((b) => b.getAttribute('aria-label')?.includes('משימה לנציג')))
    await wait()
    out.install = dialog()
    await type(dlg().querySelector('input'), '')
    out.installMissing = dialog()
    await type(dlg().querySelector('input'), 'להתקשר עכשיו')
    set({ results: { installTemplate: { ok: false, reason: 'variable_required' } } })
    await click(btn('התקנה', dlg()))
    await wait()
    out.installRefused = norm(dlg().querySelector('[role="alert"]')?.outerHTML ?? '')
    set({ results: { installTemplate: { ok: true, created: 1 } } })
    await click(btn('התקנה', dlg()))
    await wait()
    await click(cells.find((b) => b.getAttribute('aria-label')?.includes('חיבור')))
    out.calls = calls()
    cleanup()
    set({ hasAccess: false, calls: [] })
    const expired = await mount(EXPIRED)
    out.expired = norm(expired.container.querySelector('aside')!.innerHTML)
    await click(row('מענה ראשון לליד חדש').querySelector('button[aria-pressed]'))
    await click(btn('אוטומציה חדשה', expired.container.querySelector('section')!))
    await type(dlg().querySelectorAll('input')[1], 'נושא')
    await click(btn('שלח אליי בדיקה', dlg()))
    out.expiredSheet = norm(dlg().querySelector('[data-testid="subscription-expired-inline"]')?.outerHTML ?? '')
    out.expiredCalls = calls()
    expect(out).toMatchSnapshot()
  })
})
