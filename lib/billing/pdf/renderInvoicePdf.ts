import type { BillInvoiceRow, BillInvoiceLineRow } from '@/db/billing/invoices'
import type { IssuerData } from '@/lib/billing/issuer/fields'
import { renderInvoiceHtml } from './html/InvoiceTemplate'
import { dispatchHtmlToPdf } from './html/renderHtmlToPdf'
import type { DiagCtx } from './diag'

// Public renderer. After the Gotenberg + direct-to-S3 migration, this
// function no longer materializes the PDF bytes - it dispatches the
// render to Gotenberg with a webhook target (an S3 presigned PUT URL)
// and returns. Gotenberg writes the PDF directly to S3 in eu-north-1
// without the bytes ever passing through the Vercel runtime.
//
// Completion is observed asynchronously by the polling action
// (`getInvoicePdfStatusAction`) which does S3 head_object on the
// predicted key and marks the document ready when it lands.

export type RenderInvoicePdfInput = {
  invoice: BillInvoiceRow
  lines: BillInvoiceLineRow[]
  issuer?: IssuerData | null
  /**
   * Legacy fallback for the legal name. Always pass `agencies.name` here
   * so older invoices (where `issuer.name` is null) still render a sender
   * identity in the header.
   */
  fallbackName?: string
  agencyLogoPng?: Uint8Array
  /**
   * S3 presigned PUT URL where Gotenberg should upload the rendered PDF.
   * Generated by the caller for the predicted bill_documents key.
   */
  uploadUrl: string
  diagCtx?: DiagCtx | null
}

export async function renderInvoicePdf(input: RenderInvoicePdfInput): Promise<void> {
  if (input.invoice.docState === 'draft') {
    throw new Error('billing.pdf.draft_not_renderable')
  }

  const html = await renderInvoiceHtml({
    invoice: input.invoice,
    lines: input.lines,
    issuer: input.issuer ?? null,
    fallbackName: input.fallbackName ?? '',
    agencyLogoPng: input.agencyLogoPng ?? null,
  })

  await dispatchHtmlToPdf({ html, webhookUrl: input.uploadUrl }, input.diagCtx ?? null)
}
